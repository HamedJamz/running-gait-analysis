"""Validation of the pipeline against independent references.

1. Joint angles vs. the Visual3D-processed curves published with the dataset
   (RBDS###processed.txt): RMSE, mean offset, Pearson r per curve.
2. Marker-only gait events vs. force-plate events (Bland-Altman).
3. Peak vertical GRF vs. the published processed GRF.
4. Foot-strike classification (foot-strike angle) vs. the strike pattern in the
   metadata (which was obtained with a different method, so moderate agreement
   is expected).

Usage: python scripts/validate.py   (after scripts/run_all.py)
"""
from __future__ import annotations

import pickle
import sys
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402
import pandas as pd  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from rungait.io import load_participant_info  # noqa: E402
from rungait.plotting import COLORS, DOUBLE_COL, panel_label, save, style, tex  # noqa: E402

DATA = ROOT / "data" / "raw"
RES = ROOT / "results"
FIG = RES / "figures"
JOINTS = {"hip": "Hip flexion", "knee": "Knee flexion", "ankle": "Ankle dorsiflexion"}
SPEED_TAG = {2.5: "25", 3.5: "35", 4.5: "45"}


def angle_validation(results):
    rows = []
    for (sub, speed), r in results.items():
        f = DATA / f"{sub}processed.txt"
        if not f.exists():
            continue
        v3d = pd.read_csv(f, sep="\t")
        for side in "RL":
            for j in JOINTS:
                key = f"{side}.{j}.flex"
                col = f"{side}{j}AngZ{SPEED_TAG[speed]}"
                if key not in r.curves or col not in v3d:
                    continue
                ours = r.curves[key][0]
                ref = v3d[col].to_numpy()
                ok = ~np.isnan(ref)
                d = ours[ok] - ref[ok]
                rows.append(dict(subject=sub, speed=speed, side=side, joint=j,
                                 rmse=np.sqrt(np.mean(d**2)), offset=d.mean(),
                                 rmse_offset_removed=np.std(d),
                                 r=np.corrcoef(ours[ok], ref[ok])[0, 1]))
    return pd.DataFrame(rows)


def grf_validation(results, info):
    rows = []
    for (sub, speed), r in results.items():
        f = DATA / f"{sub}processed.txt"
        if not f.exists():
            continue
        v3d = pd.read_csv(f, sep="\t")
        for side in "RL":
            col = f"{side}grfY{SPEED_TAG[speed]}"
            if col in v3d and side in r.vgrf_curves:
                ref_peak = np.nanmax(v3d[col]) / 9.81          # N/kg -> BW
                ours = r.summary.loc["peak_vgrf", f"{side}_mean"]
                rows.append(dict(subject=sub, speed=speed, side=side, ours=ours, ref=ref_peak))
    return pd.DataFrame(rows)


def main():
    style()
    (ROOT / "results" / "figures").mkdir(parents=True, exist_ok=True)
    with open(RES / "cache" / "results.pkl", "rb") as fh:
        results = pickle.load(fh)
    info = load_participant_info(DATA / "RBDSinfo.txt")
    lines = ["# Validation results", "",
             "Generated by `scripts/validate.py` from all 28 participants x 3 speeds.", ""]

    # 1. Joint angles ------------------------------------------------------------
    av = angle_validation(results)
    av.to_csv(RES / "validation_angles.csv", index=False, float_format="%.3f")
    t = av.groupby("joint")[["r", "rmse", "offset", "rmse_offset_removed"]].median().loc[list(JOINTS)]
    lines += ["## 1. Sagittal joint angles vs. Visual3D (published processed curves)", "",
              "Median over 168 curves per joint (28 participants x 3 speeds x 2 sides).", "",
              "| Joint | Pearson r | RMSE (deg) | Mean offset (deg) | RMSE after removing offset (deg) |",
              "|---|---|---|---|---|"]
    for j, row in t.iterrows():
        lines.append(f"| {JOINTS[j]} | {row.r:.3f} | {row.rmse:.1f} | {row.offset:+.1f} | {row.rmse_offset_removed:.1f} |")
    lines += ["", "Waveform shapes agree closely (high r). Remaining offsets come from different "
              "segment definitions (e.g. hip joint centre regression, foot axis and neutral "
              "reference), which shift a curve without changing its shape.", ""]

    # Figure: example curves + distribution of waveform agreement
    sub_ex = "RBDS008"
    r = results[(sub_ex, 3.5)]
    v3d = pd.read_csv(DATA / f"{sub_ex}processed.txt", sep="\t")
    fig, axes = plt.subplots(1, 4, figsize=(DOUBLE_COL, 1.9),
                             gridspec_kw={"width_ratios": [1, 1, 1, 0.8], "wspace": 0.42})
    x = np.arange(101)
    ylabels = {"hip": r"Hip flexion ($^\circ$)", "knee": r"Knee flexion ($^\circ$)",
               "ankle": r"Ankle dorsiflexion ($^\circ$)"}
    for k, (ax, j) in enumerate(zip(axes[:3], JOINTS)):
        m, sd, n = r.curves[f"R.{j}.flex"]
        ax.fill_between(x, m - sd, m + sd, color=COLORS["R"], alpha=0.25, lw=0)
        ax.plot(x, m, color=COLORS["R"], lw=1.1, label="This pipeline")
        ax.plot(x, v3d[f"R{j}AngZ35"], color="k", ls=(0, (4, 2)), lw=0.9, label="Visual3D")
        ax.set_xlim(0, 100)
        ax.set_xlabel(tex("Gait cycle (%)"))
        ax.set_ylabel(ylabels[j])
        ax.minorticks_on()
        panel_label(ax, "abc"[k], x=-0.3)
    h, l_ = axes[0].get_legend_handles_labels()
    fig.legend(h, ["This pipeline (mean $\\pm$ SD)", "Visual3D (published)"], loc="upper center",
               ncol=2, bbox_to_anchor=(0.42, 1.12), fontsize=7)
    ax = axes[3]
    data = [av[av.joint == j].r.to_numpy() for j in JOINTS]
    ax.boxplot(data, widths=0.45, patch_artist=True, showfliers=True,
                    medianprops=dict(color="k", lw=0.9), boxprops=dict(facecolor="white", lw=0.6),
                    whiskerprops=dict(lw=0.6), capprops=dict(lw=0.6),
                    flierprops=dict(marker="o", ms=2, mfc="none", mec="k", mew=0.4))
    ax.set_xticks([1, 2, 3], ["Hip", "Knee", "Ankle"])
    ax.set_ylabel(r"Pearson $r$")
    ax.set_ylim(0.9, 1.0)
    panel_label(ax, "d", x=-0.38)
    save(fig, FIG / "fig_validation_angles")

    # 2. Events --------------------------------------------------------------------
    ev = pd.read_csv(RES / "event_validation.csv")
    lines += ["## 2. Marker-only gait events vs. force plate", "",
              f"{len(ev)} matched contacts. Difference = kinematic − force plate.", "",
              "| Event | Bias (ms) | SD (ms) | 95% limits of agreement (ms) |", "|---|---|---|---|"]
    fig, axes = plt.subplots(1, 2, figsize=(DOUBLE_COL * 0.66, 1.9), gridspec_kw={"wspace": 0.35})
    for k, (ax, (col, name)) in enumerate(zip(axes, [("d_ic_ms", "Initial contact"), ("d_to_ms", "Toe-off")])):
        b, s_ = ev[col].mean(), ev[col].std()
        lines.append(f"| {name} | {b:+.1f} | {s_:.1f} | {b - 1.96 * s_:+.1f} to {b + 1.96 * s_:+.1f} |")
        q = 1000 / 300                     # timing resolution of the differences (ms)
        bins = (np.arange(-16, 16) + 0.5) * q
        ax.hist(ev[col].clip(-50, 50), bins=bins, color=COLORS["light"], edgecolor=COLORS["grey"], lw=0.3)
        ax.axvline(b, color="k", lw=0.9)
        for lim in (b - 1.96 * s_, b + 1.96 * s_):
            ax.axvline(lim, color="k", ls=(0, (3, 2)), lw=0.7)
        ax.text(0.97, 0.95, f"{name}\nbias ${b:+.1f}$ ms\nSD ${s_:.1f}$ ms\n$n = {len(ev)}$",
                transform=ax.transAxes, ha="right", va="top", fontsize=6.5, linespacing=1.3,
                bbox=dict(fc="white", ec="none", pad=1.5))
        ax.set_xlabel(r"$t_{\mathrm{markers}} - t_{\mathrm{force}}$ (ms)")
        ax.set_ylabel("Contacts")
        ax.set_xlim(-50, 60)
        ax.minorticks_on()
        panel_label(ax, "ab"[k], x=-0.28)
    save(fig, FIG / "fig_validation_events")
    one_frame = 1000 / 150
    lines += ["", f"For reference, one marker frame is {one_frame:.1f} ms. The marker-only method "
              "can be used when no force plate is available (e.g. overground or field testing).", ""]

    # 3. GRF -----------------------------------------------------------------------
    gv = grf_validation(results, info)
    d = gv.ours - gv.ref
    lines += ["## 3. Peak vertical ground reaction force vs. published processed data", "",
              f"Mean difference {d.mean():+.3f} BW (SD {d.std():.3f}), r = {np.corrcoef(gv.ours, gv.ref)[0, 1]:.3f}, "
              f"n = {len(gv)} (subject x speed x side).", ""]
    q = pd.read_csv(RES / "qc_all.csv")
    lines += ["Force plausibility check (mean vertical force over the whole trial / body weight; "
              f"ideal = 1): median {q.mean_vgrf_over_bw.median():.3f}, range "
              f"{q.mean_vgrf_over_bw.min():.3f}–{q.mean_vgrf_over_bw.max():.3f}. All trials within ±7 %. "
              "The small, consistent shortfall (~2–3 %) is compatible with body mass having been "
              "measured with clothing/shoes or with a small plate offset; it is reported, not corrected.", ""]

    # 4. Foot strike -------------------------------------------------------------------
    steps = pd.read_csv(RES / "steps_all.csv")
    steps = steps[steps.valid]
    rows = []
    for (sub, sp, side), g in steps.groupby(["subject", "speed", "side"]):
        col = f"{side}FSI{SPEED_TAG[sp]}"
        lab = info.loc[sub, col] if col in info else np.nan
        rows.append(dict(subject=sub, speed=sp, side=side, fsa=g.strike_angle.mean(),
                         ours=g.strike_type.mode().iloc[0], metadata=lab))
    fs = pd.DataFrame(rows).dropna()
    ct = pd.crosstab(fs.metadata, fs.ours).reindex(index=["Rearfoot", "Midfoot", "Forefoot"],
                                                   columns=["Rearfoot", "Midfoot", "Forefoot"], fill_value=0)
    agree = (fs.ours == fs.metadata).mean()
    rf_agree = ((fs.ours == "Rearfoot") == (fs.metadata == "Rearfoot")).mean()
    lines += ["## 4. Foot-strike pattern vs. dataset metadata", "",
              "Rows: label in the dataset metadata; columns: this pipeline (foot-strike angle, "
              "Altman & Davis 2012 thresholds). Unit = subject x speed x side.", "",
              "| metadata \\ pipeline | " + " | ".join(ct.columns) + " |", "|---|---|---|---|"]
    for idx, row in ct.iterrows():
        lines.append(f"| {idx} | " + " | ".join(str(v) for v in row.values) + " |")
    lines += ["", f"Exact agreement {100 * agree:.0f} %; rearfoot vs. non-rearfoot agreement {100 * rf_agree:.0f} %. "
              "The metadata labels come from the original authors' own classification, not from "
              "the foot-strike angle, so perfect agreement is not expected; the disagreements "
              "are almost all at the midfoot/forefoot boundary.", ""]

    (RES / "VALIDATION.md").write_text("\n".join(lines))
    print("\n".join(lines))


if __name__ == "__main__":
    main()
